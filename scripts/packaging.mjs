import assert from 'node:assert/strict';
import { cp, mkdtemp, writeFile, readFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { join } from 'node:path';
import { evidence, run } from './support.mjs';
const root = fileURLToPath(new URL('../', import.meta.url));
const pack = run('npm-pack', 'npm', ['pack', '--json', '--pack-destination', evidence], { cwd: root });
assert.equal(pack.status, 0, pack.stderr);
const [manifest] = JSON.parse(pack.stdout);
const paths = manifest.files.map(file => file.path);
for (const required of ['js/index.js', 'js/index.d.ts', 'src/main.rs', 'src/request.rs', 'Cargo.toml', 'Cargo.lock', 'rust-toolchain.toml', 'LICENSE', 'README.md', `native/${process.platform}-${process.arch}/astro-cms-internal-link-structure`]) assert.ok(paths.includes(required), `Tarball missing ${required}`);
for (const path of paths) assert.ok(!/(^|\/)(node_modules|target|PROJECT\.md|evidence|reports|planning|\.env)(\/|$)|\.(tgz|log)$/u.test(path), `Private/unbuilt artifact in tarball: ${path}`);
const tarball = join(evidence, manifest.filename);
const consumer = await mkdtemp(join(evidence, 'fresh-consumer-'));
await cp(join(root, 'fixtures/static'), consumer, { recursive: true });
await writeFile(join(consumer, 'package.json'), JSON.stringify({ name: 'fresh-astro-consumer', private: true, type: 'module', scripts: { build: 'astro build' }, dependencies: { astro: '7.3.5', 'astro-cms-internal-link-structure': `file:${tarball}` } }, null, 2));
const install = run('fresh-npm-install', 'npm', ['install', '--ignore-scripts'], { cwd: consumer });
assert.equal(install.status, 0, install.stderr);
const installed = join(consumer, 'node_modules/astro-cms-internal-link-structure');
const { realpath } = await import('node:fs/promises');
assert.equal(await realpath(installed), installed, 'Consumer package must be an extracted tarball, not a source symlink');
const success = run('fresh-astro-pass', 'npm', ['run', 'build'], { cwd: consumer });
assert.equal(success.status, 0, `${success.stdout}\n${success.stderr}`);
assert.equal(JSON.parse(await readFile(join(consumer, 'reports/links.json'), 'utf8')).gates.violated, false);
const failure = run('fresh-astro-broken-enforce', 'npm', ['run', 'build'], { cwd: consumer, env: { BROKEN: '1' } });
assert.notEqual(failure.status, 0);
const report = JSON.parse(await readFile(join(consumer, 'reports/links.json'), 'utf8'));
assert.equal(report.gates.violated, true);
assert.equal(report.issues.brokenPaths.length, 4); assert.equal(report.issues.brokenFragments.length, 4);
const summary = { tarball, consumer, installed, successExit: success.status, brokenEnforceExit: failure.status, files: paths };
await writeFile(join(evidence, 'packaging-result.json'), JSON.stringify(summary, null, 2) + '\n');
console.log(JSON.stringify(summary, null, 2));
